def test_actual_predictions_and_independently_recorded_quality(actual_comparison):
    # Independently recorded plan v1.7 check sheet A (not generated by this code).
    references = {
        "S01": ((793.798554, 561.300421), 29, 0),
        "S02": ((2000.451129, 629.474158), 32, 1),
    }
    for frame in actual_comparison["frames"]:
        position, count, transient = references[frame["observation_id"]]
        assert [frame["prediction"]["x"], frame["prediction"]["y"]] == pytest.approx(
            position, abs=1e-6
        )
        quality = frame["quality"]
        assert quality["pixel_count"] == count
        assert quality["flag_counts"]["NONFUNC"] == 1
        assert quality["flag_counts"]["TRANSIENT"] == transient
        assert quality["flag_counts"]["SOURCE"] == count
        assert quality["flag_counts"]["OVERFLOW"] == 0
        assert quality["flag_counts"]["NONLINEAR"] == 0
        assert quality["flag_counts"]["OUTLIER"] == 0
        assert quality["clipped_pixel_count"] == 0
        assert (
            quality["image_nonfinite"]
            == quality["variance_nonfinite"]
            == quality["variance_nonpositive"]
            == 0
        )
        # NF and T on the second exposure overlap: do not sum flags as bad pixels.
        assert quality["display"] == {
            "retained": count,
            "excluded": 0,
            "review_required": 1,
            "reason": "Finite original pixels retained; non-informational flags and invalid variance require review.",
        }
        assert quality["quantitative"]["status"] == "not_validated"
    assert actual_comparison["scientific_status"] == "association_insufficient"


def test_actual_schema_native_pixels_and_source_provenance(actual_comparison):
    json.dumps(actual_comparison, allow_nan=False)
    for frame in actual_comparison["frames"]:
        metadata = frame["metadata"]
        assert metadata["pipeline_version"] == "7.0.5"
        assert metadata["timesys"] == "UTC"
        assert metadata["unit"].replace(" ", "") == "MJy/sr"
        assert metadata["epsf"]["rows"] == 441
        assert metadata["epsf"]["oversampling"] == {"x": 5, "y": 5}
        assert metadata["wcs"]["has_sip"] is True
        assert metadata["wcs"]["round_trip_error_px"] < 1e-6
        assert (
            frame["calibration"]["sha256"]
            == "19195d253892883586aa2183cb66238b32f6032ade62d490b36b85b0dd18f212"
        )
        path = ROOT / frame["provenance"]["local_relative_path"]
        with fits.open(path, memmap=False) as hdul:
            crop = frame["cutout"]
            x0, y0 = crop["native_origin"]["x"], crop["native_origin"]["y"]
            for name in ("IMAGE", "FLAGS", "VARIANCE", "ZODI"):
                original = hdul[name].data[y0 : y0 + crop["height"], x0 : x0 + crop["width"]]
                assert crop[name] == _json_array(original)
            assert [definition["name"] for definition in frame["quality"]["flag_definitions"]] == [
                str(hdul["FLAGS"].header[key]).strip()
                for key in hdul["FLAGS"].header
                if key.startswith("MSKN")
            ]
        assert frame["prediction"]["omitted"] == [
            "observer_parallax",
            "radial_velocity",
            "full_covariance",
        ]
    # The display crop can clip while the smaller quantitative review window does not.
    assert actual_comparison["frames"][1]["cutout"]["width"] == 80
    assert actual_comparison["frames"][1]["cutout"]["clipped_pixel_count"] == 81


def test_alternate_detector_wcs_does_not_inherit_sky_sip():
    # An independently understandable WCS: sky has SIP while detector A is identity.
    header = fits.Header(
        {
            "NAXIS": 2,
            "NAXIS1": 11,
            "NAXIS2": 11,
            "CTYPE1": "RA---TAN-SIP",
            "CTYPE2": "DEC--TAN-SIP",
            "CRPIX1": 1.0,
            "CRPIX2": 1.0,
            "CRVAL1": 0.0,
            "CRVAL2": 0.0,
            "CDELT1": -0.001,
            "CDELT2": 0.001,
            "A_ORDER": 2,
            "B_ORDER": 2,
            "A_2_0": 0.1,
            "B_0_2": 0.1,
            "CTYPE1A": "LINEAR",
            "CTYPE2A": "LINEAR",
            "CRPIX1A": 1.0,
            "CRPIX2A": 1.0,
            "CRVAL1A": 0.0,
            "CRVAL2A": 0.0,
            "CDELT1A": 1.0,
            "CDELT2A": 1.0,
        }
    )
    original_sky = WCS(header)
    alternate = _alternate_wcs(header, fits.HDUList([fits.PrimaryHDU()]), "A")
    assert original_sky.sip is not None
    assert alternate.sip is None
    assert tuple(float(value) for value in alternate.all_pix2world(3, 4, 0)) == (3, 4)
    assert header["A_2_0"] == 0.1  # Do not mutate the input/primary header.


def test_bilinear_calibration_has_explicit_boundary_and_nonfinite_handling():
    assert _bilinear(np.array([[2, 4], [6, 8]], dtype=np.float32), 0.25, 0.5) == 4.5
    assert _bilinear(np.array([[2, 4], [6, np.nan]]), 0.25, 0.5) is None
    assert _bilinear(np.ones((2, 2)), -0.1, 0.5) is None
    assert _json_array(np.array([[np.nan, np.inf, -np.inf, 0.0]])) == [[None, None, None, 0.0]]


def test_flag_declarations_overlap_informational_source_and_unknown_bits():
    header = fits.Header(
        {
            "MSKN0000": "TRANSIENT",
            "MSKM0000": 1,
            "MSKN0006": "NONFUNC",
            "MSKM0006": 64,
            "MSKN0021": "SOURCE",
            "MSKM0021": 2097152,
        }
    )
    definitions = flag_definitions(header)
    image = np.ones((3, 3))
    flags = np.full((3, 3), 2097152, dtype=np.uint32)
    flags[1, 1] |= 65  # Two flags on one pixel; SOURCE remains informational.
    flags[0, 0] |= 8  # Undeclared bit is reviewed rather than silently good.
    planes = {"IMAGE": image, "VARIANCE": image.copy(), "FLAGS": flags}
    quality = quality_summary(planes, (1, 1), definitions, radius=3)
    assert quality["flag_counts"] == {"TRANSIENT": 1, "NONFUNC": 1, "SOURCE": 9}
    assert quality["display"]["retained"] == 9
    assert quality["display"]["review_required"] == 2
    assert quality["undeclared_bit_pixels"] == 1
    assert quality["clipped_pixel_count"] > 0


def test_source_integrity_and_path_boundary(tmp_path):
    directory = tmp_path / "data"
    directory.mkdir()
    source = directory / "source.bin"
    source.write_bytes(b"actual-original")
    record = {
        "local_relative_path": "data/source.bin",
        "bytes": 15,
        "sha256": hashlib.sha256(b"actual-original").hexdigest(),
    }
    assert verify_source(tmp_path, record) == source
    source.write_bytes(b"changed-content")
    with pytest.raises(ValueError, match="source_hash_mismatch"):
        verify_source(tmp_path, record)
    with pytest.raises(ValueError, match="source_path_outside_data"):
        verify_source(tmp_path, {**record, "local_relative_path": "../escape.bin"})


